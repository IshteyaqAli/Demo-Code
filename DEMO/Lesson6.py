# Built in functions in python
# They are as follows:
print("hello world") # It's output will be hello world
input("Enter your name: ") # It's output will be the name entered by the user 
len("hello")
print(len("hello")) # It's output will be 5
type(5) # It's output will be <class 'int'>
print(type(5)) # It's output will be <class 'int'>
int("5") # It's output will be 5
print(int("5")) # It's output will be 5
float("5.0") # It's output will be 5.0
print(float("5.0")) # It's output will be 5.0
str(5) # It's output will be "5"
print(str(5))
list((1,2,3)) # It's output will be [1, 2, 3]
print(list((1,2,3)))
tuple((1,2,3)) # It's output will be (1, 2, 3)
print(tuple((1,2,3)))
dict([(1, 10), (2, 20), (3, 30)]) # It's output will be {1: 10, 2: 20, 3: 30}
print(dict([(1, 10), (2, 20), (3, 30)]))
abs(-5) # It's output will be 5
print(abs(-5)) # It's output will be 5
pow(2, 3) # It's output will be 8
print(pow(2, 3)) # It's output will be 8
min(1, 2, 3, 4, 5) # It's output will be 1
max(1, 2, 3, 4, 5) # It's output will be 5
print(min(1, 2, 3, 4, 5)) # It's output will be 1
print(max(1, 2, 3, 4, 5)) # It's output will be 5
round(5.5) # It's output will be 6
print(round(5.5)) # It's output will be 6
divmod(5, 2) # It's output will be (2, 1)
print(divmod(5, 2)) # It's output will be (2, 1)
bin(5) # It's output will be 0b101
print(bin(5)) # It's output will be 0b101
oct(5) # It's output will be 0o5
print(oct(5)) # It's output will be 0o5
hex(5) # It's output will be 0x5
print(hex(5)) # It's output will be 0x5 
id(5) # It's output will be the memory address of 5
print(id(5)) # It's output will be the memory address of 5
ord("a") # It's output will be 97 an ascii value of a
print(ord("a")) # It's output will be 97
sum([1, 2, 3, 4, 5]) # It's output will be 15
print(sum([1, 2, 3, 4, 5])) # It's  output will be 15   
help(print) # It's output will be the documentation of print function   
